final_serializable_messages = []

# Process the first message (initial user request)
user_message = response['messages'][0]
final_serializable_messages.append({
    'type': user_message.__class__.__name__,
    'content': user_message.content,
    'agent': getattr(user_message, 'name', None) # Will be None for user messages
})

# Iterate through the rest of the messages, inferring supervisor actions
for i in range(len(response['messages']) - 1):
    # Safely get current_message_sender, handling cases where name is None
    raw_current_sender_name = getattr(response['messages'][i], 'name', None)
    if raw_current_sender_name is None:
        if i == 0: # This is the first message (user's query)
            current_message_sender_str = 'user'
        else: # An agent message with an explicit name=None
            current_message_sender_str = 'unnamed_agent'
    else:
        current_message_sender_str = raw_current_sender_name

    next_message = response['messages'][i+1]
    next_agent_name = getattr(next_message, 'name', None)

    if next_agent_name: # Only insert supervisor action if there's a next agent producing a message
        final_serializable_messages.append({
            'type': 'SupervisorAction',
            'content': f"Supervisor received {'user request' if current_message_sender_str == 'user' else 'output from ' + current_message_sender_str} and routed to '{next_agent_name}'.",
            'agent': 'supervisor'
        })

    # Add the actual agent's message
    final_serializable_messages.append({
        'type': next_message.__class__.__name__,
        'content': next_message.content,
        'agent': next_agent_name
    })

serializable_response = {'messages': final_serializable_messages}
print(json.dumps(serializable_response, indent=2))

